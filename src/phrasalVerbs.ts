const ORDER: Level[] = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2'];

/** Меньше — лист не лист: на A1 у «set» нет ни одного, берём самые простые. */
const MIN_ENTRIES = 6;

/**
 * Глаголы гнезда для уровня: всё до него включительно, от простых к трудным.
 * Если таких меньше шести — добираем самыми простыми следующего уровня.
 */
export function phrasalEntriesFor(group: PhrasalGroup, level: Level): string[] {
  const rank = (entry: [string, Level]) => ORDER.indexOf(entry[1]);
  const sorted = [...group.entries].sort((a, b) => rank(a) - rank(b));
  const within = sorted.filter((entry) => rank(entry) <= ORDER.indexOf(level));
  const chosen = within.length >= MIN_ENTRIES ? within : sorted.slice(0, MIN_ENTRIES);
  return chosen.map(([term]) => term);
}

export function phrasalGroup(key: string): PhrasalGroup | undefined {
  return PHRASAL_GROUPS.find((group) => group.key === key);
}
