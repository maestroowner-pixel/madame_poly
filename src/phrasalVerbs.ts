const ORDER: Level[] = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2'];

/** Меньше — лист не лист: на A1 у «set» нет ни одного, берём самые простые. */
const MIN_ENTRIES = 6;

/**
 * Больше — модель не успевает дописать к каждому глаголу упражнение: в «up»
 * на C2 их под сорок. Остаются глаголы своего уровня, потом ближнего ниже.
 */
const MAX_ENTRIES = 32;

/**
 * Глаголы гнезда для уровня, от простых к трудным. До B2 — всё до уровня
 * включительно: повторить простые не лишнее. На C1 и C2 — свой уровень и
 * один ниже: человеку с C2 «get up» не нужен, а с ним лист вышел бы на
 * шестьдесят записей. Если глаголов меньше шести — добираем ближайшими.
 */
export function phrasalEntriesFor(group: PhrasalGroup, level: Level): string[] {
  const target = ORDER.indexOf(level);
  const lowest = target >= ORDER.indexOf('C1') ? target - 1 : 0;
  const rank = (entry: [string, Level]) => ORDER.indexOf(entry[1]);
  const inRange = group.entries.filter((entry) => rank(entry) >= lowest && rank(entry) <= target);
  // Сначала свой уровень, потом ниже, потом — если совсем мало — выше.
  const distance = (entry: [string, Level]) => (rank(entry) <= target ? target - rank(entry) : 10 + rank(entry) - target);
  const byCloseness = [...group.entries].sort((a, b) => distance(a) - distance(b));
  const chosen = (inRange.length >= MIN_ENTRIES ? byCloseness.filter((entry) => inRange.includes(entry)) : byCloseness)
    .slice(0, Math.max(MIN_ENTRIES, Math.min(inRange.length, MAX_ENTRIES)));
  return chosen.sort((a, b) => rank(a) - rank(b)).map(([term]) => term);
}

export function phrasalGroup(key: string): PhrasalGroup | undefined {
  return PHRASAL_GROUPS.find((group) => group.key === key);
}
