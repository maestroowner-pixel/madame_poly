import type { Level } from './types';

/**
 * Шестьсот фразовых глаголов английского — закреплённый список: триста самых
 * ходовых (A1–B2 и начало C1) и ещё триста идиоматичных и книжных для C1–C2,
 * чтобы лист «get» на B1 всякий раз учил одни и те же get up, get over, а не
 * то, что модель вспомнит. Уровни — по English Vocabulary Profile и учебникам
 * (Murphy, «English Phrasal Verbs in Use»), сверены по памяти, не по базе.
 *
 * Гнёзда — по глаголу для главных (carry, hold, call, work — одной темой: у
 * каждого их мало); остальные (wake up, find out, calm down) — по частице:
 * тема «wake» из одного глагола была бы пустой.
 * Запись — как в листе: sth / sb на месте дополнения, «put sth off», если
 * дополнение встаёт между глаголом и частицей, «look after sb», если нет.
 */
export interface PhrasalGroup {
  /** Часть идентификатора темы: pv-get, pv-in-on. */
  key: string;
  /** Как называется в теме: «get», «in, on». */
  title: string;
  /** Гнездо глагола или частицы — от этого зависят неверные варианты. */
  by: 'verb' | 'particle';
  entries: [term: string, level: Level][];
}

