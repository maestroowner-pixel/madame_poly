import type { Level } from './types';

import { EXPLANATION_LANGUAGE_NAME, locale } from './i18n';

/**
 * Ключи и настройки. Приложение личное, поэтому ключи лежат в .env и попадают
 * в бандл (переменные с префиксом EXPO_PUBLIC_ инлайнятся при сборке).
 * Для публикации в сторах так делать нельзя — понадобится прокси-бэкенд.
 */
export const OPENAI_API_KEY = process.env.EXPO_PUBLIC_OPENAI_API_KEY ?? '';
export const ANTHROPIC_API_KEY = process.env.EXPO_PUBLIC_ANTHROPIC_API_KEY ?? '';

/**
 * Голос собеседницы. Один на все четыре языка: у неё одно лицо во всех ролях,
 * значит и голос должен быть один — иначе на немецком отвечал бы мужчина.
 * Голоса OpenAI не привязаны к языку, `nova` одинаково читает все четыре.
 */
export const OPENAI_TTS_VOICE = 'nova';

/** Модель диалога. */
export const CLAUDE_MODEL = 'claude-sonnet-5';

/**
 * Ответы разговорные и короткие, поэтому потолок низкий — усечения не будет,
 * а латентность и стоимость ниже.
 */
export const CLAUDE_MAX_TOKENS = 4096;

/**
 * Язык, на котором ИИ объясняет ошибки. Идёт за языком интерфейса: разбор
 * бесполезен, если написан не на том языке, на котором человек читает.
 */
export const EXPLANATION_LANGUAGE = EXPLANATION_LANGUAGE_NAME[locale];

/** Сколько последних сообщений отправлять в модель как контекст диалога. */
export const HISTORY_WINDOW = 20;

/** Автоматически проигрывать ответ ИИ после получения. */
export const AUTOPLAY_TTS = true;

// --- Режим свободных рук ---
// Беседа идёт без тапов: приложение слушает, ловит паузу, отвечает и снова
// слушает. Границу реплики определяем по уровню входного сигнала.

/** Как часто опрашивать уровень записи, мс. */
export const METERING_INTERVAL_MS = 100;

/**
 * Насколько речь громче своих же пауз, dB. Конец фразы ловится по спаду от
 * самого громкого в этой реплике, а не по абсолютному уровню: микрофоны отдают
 * разные шкалы, и порог в децибелах, подобранный на одном устройстве, на
 * другом либо не слышит голоса, либо не слышит пауз. Спад одинаков везде.
 */
export const SPEECH_DROP_DB = 12;

/**
 * На сколько оседает пик за отсчёт, dB. Без этого одиночный хлопок задрал бы
 * шкалу до конца реплики и речь после него сошла бы за тишину. Оседать он
 * должен медленнее, чем длится пауза: иначе к её концу фон снова дотянется до
 * пика и сойдёт за речь.
 */
export const PEAK_DECAY_DB = 0.2;

/**
 * На сколько поднимается отметка тишины за отсчёт, dB. Вниз она падает сразу,
 * вверх ползёт — чтобы шкала восстанавливалась, если в комнате стало шумнее.
 */
export const QUIET_RISE_DB = 0.15;

/** Сколько тишины после речи завершает реплику, мс. */
export const SILENCE_HOLD_MS = 1300;

/** Минимум речи, чтобы не реагировать на кашель и стук, мс. */
export const MIN_SPEECH_MS = 400;

/** Жёсткий потолок одной реплики, мс. */
export const MAX_TURN_MS = 30000;

// --- Заставка ---

/**
 * Сколько держится заставка, мс. Гонг подрезан под ту же длину, поэтому
 * картинка и звук заканчиваются вместе.
 */
export const SPLASH_HOLD_MS = 3000;

/**
 * Темп чтения диктанта по уровням. Медленная речь — половина сложности
 * аудирования: на A1 тот же текст на нормальной скорости не разобрать.
 */
export const LISTENING_SPEED: Record<Level, number> = {
  A1: 0.75,
  A2: 0.85,
  B1: 0.95,
  B2: 1,
  C1: 1.1,
  C2: 1.15,
};
